#!/bin/bash
# Reset the integration database: schema (idempotent), roles, functions and
# seed data. Self-contained -- safe to run on an empty database.
PSQL="${PSQL:-/home/z/my-project/tools/pgsql/bin/psql}"
$PSQL -h 127.0.0.1 -p 5433 -U postgres -d postgres -q -v ON_ERROR_STOP=1 <<'EOF'
select 'CREATE DATABASE testdb'
where not exists (select from pg_database where datname = 'testdb') \gexec
EOF

$PSQL -h 127.0.0.1 -p 5433 -U postgres -d testdb -q -v ON_ERROR_STOP=1 <<'EOF'
-- roles (PostgREST security model)
do $$ begin
  if not exists (select from pg_roles where rolname='anon') then create role anon nologin; end if;
  if not exists (select from pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
  if not exists (select from pg_roles where rolname='authenticator') then create role authenticator login password 'pw'; end if;
end $$;
grant anon, authenticated to authenticator;

-- optional config table (PGRST_DB_CONFIG)
create schema if not exists postgrest;
create table if not exists postgrest.config (name text primary key, setting text not null);

-- exposed schemas
create schema if not exists api;
create schema if not exists api2;

-- main test tables
create table if not exists api.directors (id int primary key, name text not null);
create table if not exists api.films (
  id int primary key generated by default as identity,
  title text not null, year int, director_id int references api.directors(id),
  rating numeric(3,1), tags text[], search tsvector
);
create table if not exists api.actors (id int primary key, name text not null);
create table if not exists api.performances (
  film_id int references api.films(id), actor_id int references api.actors(id), salary int,
  primary key (film_id, actor_id)
);
create table if not exists api.reviews (
  id int primary key generated by default as identity,
  film_id int not null references api.films(id),
  body text not null, stars int check (stars between 1 and 5), user_id int
);
-- second schema (Content-Profile / Accept-Profile tests)
create table if not exists api2.films (id int primary key, title text not null);

-- functions: scalar, overloaded, setof, table, computed relationship
create or replace function api.hello(name text default 'world') returns text as $$ select 'hello, ' || name $$ language sql stable;
create or replace function api.hello(name text, greeting text) returns text as $$ select greeting || ', ' || name $$ language sql stable;
create or replace function api.add(a int, b int) returns int as $$ select a + b $$ language sql stable;
create or replace function api.films_by_year(min_year int) returns setof api.films as $$ select * from api.films where year >= min_year $$ language sql stable;
create or replace function api.stats() returns table(avg_rating numeric, n bigint) as $$ select avg(rating), count(*) from api.films $$ language sql stable;
create or replace function api.voidfn() returns void as $$ begin end $$ language plpgsql;
create or replace function api.films_of(d api.directors) returns setof api.films as $$ select * from api.films where director_id = d.id $$ language sql stable;
create or replace procedure api.spin() language plpgsql as $$ begin end $$;

-- grants
grant usage on schema api to anon, authenticated;
grant usage on schema api2 to anon, authenticated;
grant usage on all sequences in schema api to anon, authenticated;
grant all on all tables in schema api to anon, authenticated;
grant all on all tables in schema api2 to anon, authenticated;
grant execute on all functions in schema api to anon, authenticated;

-- seed
truncate api.reviews, api.performances, api.actors, api.films, api.directors restart identity cascade;
insert into api.directors(id,name) values (1,'Nolan'),(2,'Villeneuve'),(3,'Greta Gerwig');
insert into api.films(id,title,year,director_id,rating,tags,search) values
 (1,'Inception',2010,1,8.8,'{scifi,thriller}',to_tsvector('Inception dream heist')),
 (2,'Interstellar',2014,1,8.6,'{scifi,drama}',to_tsvector('Interstellar space wormhole')),
 (3,'Dune',2021,2,8.0,'{scifi,desert}',to_tsvector('Dune sand arrakis')),
 (4,'Barbie',2023,3,6.8,'{comedy}',to_tsvector('Barbie doll comedy'));
insert into api.actors(id,name) values (1,'DiCaprio'),(2,'Chalamet'),(3,'Robbie');
insert into api.performances values (1,1,5000),(3,2,9000),(4,3,7000);
insert into api.reviews(film_id,body,stars) values (1,'mIND BEND',5),(1,'fine',3),(3,'epic',5),(4,'fun',4);
truncate api2.films;
insert into api2.films(id,title) values (1,'Alt Film');

-- keep identity sequences past the explicit ids
select setval(pg_get_serial_sequence('api.films','id'), (select max(id) from api.films));
select setval(pg_get_serial_sequence('api.reviews','id'), (select max(id) from api.reviews));

-- RLS: authenticated sees only own reviews; anon full access
grant authenticated to authenticator;
grant usage on schema api to authenticated;
grant all on all tables in schema api to authenticated;
grant all on all sequences in schema api to authenticated;
alter table api.reviews enable row level security;
drop policy if exists own_reviews on api.reviews;
create policy own_reviews on api.reviews
  using (user_id = coalesce(nullif(current_setting('request.jwt.claim.user_id', true), '')::int, -1))
  with check (user_id = coalesce(nullif(current_setting('request.jwt.claim.user_id', true), '')::int, -1));
update api.reviews set user_id = 42 where id % 2 = 1;
update api.reviews set user_id = 7 where id % 2 = 0 and user_id is null;
grant select on api.reviews to authenticated, anon;
grant select on api.films to authenticated, anon;
drop policy if exists anon_all_reviews on api.reviews;
create policy anon_all_reviews on api.reviews to anon using (true) with check (true);
EOF
echo "db reset ok"
